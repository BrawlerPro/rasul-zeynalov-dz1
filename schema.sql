CREATE SCHEMA IF NOT EXISTS rasul_zeynalov;
SET search_path TO rasul_zeynalov;
CREATE TABLE IF NOT EXISTS users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, login text NOT NULL, password_hash text NOT NULL,
 role text NOT NULL CHECK(role IN ('staff','customer'))
);
CREATE TABLE IF NOT EXISTS categories (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL, sla_hours integer NOT NULL CHECK(sla_hours>0)
);
CREATE TABLE IF NOT EXISTS tickets (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id integer NOT NULL REFERENCES users(id),
 category_id integer NOT NULL REFERENCES categories(id),
 title text NOT NULL CHECK(length(title)>0), body text NOT NULL,
 status text NOT NULL DEFAULT 'new' CHECK(status IN ('new','in_progress','closed')),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS comments (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id integer NOT NULL REFERENCES tickets(id),
 user_id integer NOT NULL REFERENCES users(id),
 body text NOT NULL CHECK(length(body)>0),
 created_at timestamptz NOT NULL DEFAULT now()
);
